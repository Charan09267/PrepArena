package net.edupilot.aiservice.service;

import lombok.RequiredArgsConstructor;
import net.edupilot.aiservice.dto.request.InterviewEvaluationRequest;
import net.edupilot.aiservice.dto.response.InterviewEvaluationResponse;
import net.edupilot.aiservice.exception.AiServiceException;
import net.edupilot.aiservice.prompt.InterviewEvaluationPromptBuilder;
import org.springframework.ai.chat.client.ChatClient;
import org.springframework.stereotype.Service;

/**
 * Service responsible for evaluating mock interviews using an AI language model.
 *
 * <p>Builds an evaluation prompt from the submitted interview data, sends it
 * to the configured AI model through Spring AI, and maps the generated result
 * to a structured response object.</p>
 */
@Service
@RequiredArgsConstructor
public class InterviewEvaluationService {

    private final ChatClient chatClient;
    private final InterviewEvaluationPromptBuilder promptBuilder;

    /**
     * Evaluates the submitted interview by generating an AI-based assessment.
     *
     * @param request interview details and responses to evaluate
     * @return structured interview evaluation generated by the AI model
     * @throws AiServiceException if prompt generation or AI evaluation fails
     */
    public InterviewEvaluationResponse evaluateInterview(
            InterviewEvaluationRequest request) {

        try {
            // Construct the prompt using the interview evaluation requirements
            // and the data supplied in the request.
            String prompt = promptBuilder.buildPrompt(request);

            // Send the prompt to the configured language model and map its
            // response to the expected evaluation response type.
            return chatClient
                    .prompt()
                    .user(prompt)
                    .call()
                    .entity(InterviewEvaluationResponse.class);

        } catch (Exception exception) {
            // Wrap underlying failures in a service-specific exception so
            // they can be handled consistently by the application's error handling.
            throw new AiServiceException(
                    "Failed to evaluate interview",
                    exception
            );
        }
    }
}